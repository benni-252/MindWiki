import { useWiki } from '../store'

export function Toasts(): React.JSX.Element {
  const toasts = useWiki((s) => s.toasts)
  return (
    <div className="toasts" aria-live="polite">
      {toasts.map((t) => (
        <div key={t.id} className={`toast ${t.kind}`}>
          {t.text}
        </div>
      ))}
    </div>
  )
}
